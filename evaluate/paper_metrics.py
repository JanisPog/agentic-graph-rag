"""WixQA paper metrics — the exact evaluation suite from the WixQA paper (§4.3).

Two families:

  Lexical (no LLM cost), generated answer vs. gold answer
    • F1        token-level F1 (SQuAD-style normalisation)
    • BLEU      sentence BLEU-4 with NLTK-style method-1 smoothing
    • ROUGE-1   unigram overlap F-measure
    • ROUGE-2   bigram overlap F-measure

  LLM-judged (0–1), one call each, using the paper's Appendix C / D prompts
    • Factuality      query + generated + gold  → factual alignment of answer to gold
    • Context Recall  query + retrieved context + gold → does context contain the gold info

The lexical metrics are pure-Python implementations of the standard definitions
(no external deps); absolute values may differ marginally from the paper's
FlashRAG implementation but are directionally comparable. The judges reproduce
the Appendix C/D prompts verbatim; the paper used GPT-4o, here the judge is
whatever CHAT_BACKEND points to (use a strong model for fidelity).
"""
from __future__ import annotations

import logging
import math
import re
from collections import Counter

log = logging.getLogger("wixqa.paper_metrics")

# ── Tokenisation / normalisation ──────────────────────────────────────────────

_ARTICLES_RE = re.compile(r"\b(a|an|the)\b")
_WORD_RE = re.compile(r"\w+", re.UNICODE)


def _squad_normalize(text: str) -> list[str]:
    """SQuAD-style normalisation for F1: lowercase, drop articles & punctuation."""
    text = (text or "").lower()
    text = _ARTICLES_RE.sub(" ", text)
    return _WORD_RE.findall(text)


def _tokenize(text: str) -> list[str]:
    """Plain lowercase word tokenisation for BLEU / ROUGE."""
    return _WORD_RE.findall((text or "").lower())


def _ngrams(tokens: list[str], n: int) -> list[tuple]:
    return [tuple(tokens[i:i + n]) for i in range(len(tokens) - n + 1)]


# ── Lexical metrics ───────────────────────────────────────────────────────────

def f1_score(pred: str, gold: str) -> float:
    """Token-level F1 between prediction and gold (SQuAD-style)."""
    p, g = _squad_normalize(pred), _squad_normalize(gold)
    if not p or not g:
        return float(p == g)
    common = Counter(p) & Counter(g)
    same = sum(common.values())
    if same == 0:
        return 0.0
    precision = same / len(p)
    recall = same / len(g)
    return 2 * precision * recall / (precision + recall)


def rouge_n(pred: str, gold: str, n: int) -> float:
    """ROUGE-N F-measure over n-gram overlap."""
    p, g = _ngrams(_tokenize(pred), n), _ngrams(_tokenize(gold), n)
    if not p or not g:
        return 0.0
    overlap = sum((Counter(p) & Counter(g)).values())
    if overlap == 0:
        return 0.0
    precision = overlap / len(p)
    recall = overlap / len(g)
    return 2 * precision * recall / (precision + recall)


def bleu_score(pred: str, gold: str, max_n: int = 4) -> float:
    """Sentence BLEU-4 with NLTK method-1 smoothing (epsilon for zero counts)."""
    p, g = _tokenize(pred), _tokenize(gold)
    if not p:
        return 0.0
    precisions: list[float] = []
    for n in range(1, max_n + 1):
        pn, gn = _ngrams(p, n), _ngrams(g, n)
        if not pn:
            precisions.append(1e-9)
            continue
        overlap = sum((Counter(pn) & Counter(gn)).values())
        # method-1 smoothing: replace a zero numerator with a small epsilon
        precisions.append((overlap if overlap > 0 else 0.1) / len(pn))

    geo_mean = math.exp(sum(math.log(pr) for pr in precisions) / max_n)

    # Brevity penalty (single reference)
    c, r = len(p), len(g)
    bp = 1.0 if c > r else math.exp(1 - r / c) if c > 0 else 0.0
    return bp * geo_mean


def lexical_metrics(pred: str, gold: str) -> dict[str, float]:
    """All four lexical paper metrics in one call."""
    return {
        "f1":      f1_score(pred, gold),
        "bleu":    bleu_score(pred, gold),
        "rouge1":  rouge_n(pred, gold, 1),
        "rouge2":  rouge_n(pred, gold, 2),
    }


# ── LLM judges (paper Appendix C / D, verbatim prompts) ───────────────────────

# Note: the paper's prompts present a 1–5 rubric but instruct "Assign a rating
# (0-1)", and the reported scores are on a 0–1 scale. We follow the 0–1
# instruction and request a continuous score in [0, 1]; the 1–5 bands serve as
# the rubric. Output is requested as JSON for reliable parsing.

_FACTUALITY_PROMPT = """\
ROLE
You are a Factual Alignment Expert. Your job is to evaluate how well an AI response includes the essential information from a ground truth answer (GT answer) according to a given user query.
Note that the Ground Truth (GT Answer), is the "Correct" answer generated by an expert, and was created to evaluate the model, and is NOT part of the AI response or the context.

TASK DESCRIPTION
You will be presented with three elements: a question, a GT answer, and an AI response. Determine how well the AI response includes the essential information from the GT answer that helps to solve the user's query. In case of any additional or extra information present in the AI response, only make sure it's not preventing the user from solving his query.

EVALUATION CRITERIA
5: Complete Match - All essential information from GT answer appears in AI response, providing complete solution to the query
4: Strong Match - Most essential information is present, with only minor details missing that don't impact the solution significantly
3: Partial Match - Core information is present but missing some important details that would help better solve the query
2: Limited Match - Only basic or partial information present, missing several essential elements needed for the solution
1: Poor Match - Missing most essential information or contains incorrect information that could mislead the user

INSTRUCTIONS
1. Read the question carefully and analyze the ground truth answer to identify all key information elements that help solve the query
2. Compare the AI response (candidate answer) against the ground truth, focusing on presence of important information
3. Evaluate the completeness and accuracy of the information transfer
4. Assign a rating (0-1) based on how well important information is preserved
5. Provide a brief explanation focusing on factuality

QUESTION:
{question}

GT ANSWER:
{gold}

AI RESPONSE:
{answer}

Respond with JSON only: {{"score": <float between 0 and 1>, "explanation": "<brief>"}}"""

_CONTEXT_RECALL_PROMPT = """\
ROLE You are a Context Evaluation Expert. Your job is to assess how well a retrieved context contains the essential information present in a ground truth answer (GT answer).

TASK DESCRIPTION You will be presented with three pieces of information: a user query, its ground truth answer, and a retrieved context (that will be used to create an AI response from). Determine how well the essential information from the GT answer appears in the retrieved context. Additional information in the retrieved context should not affect the scoring.

EVALUATION CRITERIA
5: Complete Match - All essential information from the GT answer is present in the retrieved context. The context fully enables answering the user's question.
4: Strong Match - All essential information is present, but some minor details are missing. The context still effectively answers the user's question.
3: Partial Match - Most essential information is present, but some important details are missing. The context partially answers the user's question.
2: Weak Match - Only basic or limited essential information is present. The context provides insufficient information to properly answer the user's question.
1: No Match - Essential information is missing or incorrect. The context cannot be used to answer the user's question.

INSTRUCTIONS
1. Read the question to understand the idea of what the user asks for
2. Break down the GT answer into essential information (key facts, main concepts, direct answers).
3. Check if these information pieces appear in the retrieved context
4. Focus only on finding the ground truth information in the context - ignore any additional or extra information present in the retrieved context
5. Assign a rating (0-1) based on information coverage and relevance

USER QUERY:
{question}

GT ANSWER:
{gold}

RETRIEVED CONTEXT:
{context}

Respond with JSON only: {{"score": <float between 0 and 1>, "explanation": "<brief>"}}"""


def _coerce_score(value) -> float:
    """Coerce a judge 'score' into a float in [0,1].

    Tolerates strings like '0.9', '0.9 (Strong Match)', '4/5', or a bare 1–5
    rating (mapped to 0–1). Raises ValueError if no number can be extracted.
    """
    if isinstance(value, (int, float)):
        num = float(value)
    else:
        m = re.search(r"\d+(?:\.\d+)?", str(value))
        if not m:
            raise ValueError(f"no number in score {value!r}")
        num = float(m.group(0))
    # The prompt asks for a 0–1 float, so values in [0,1] are taken as-is. Only a
    # clearly out-of-range value (>1) is treated as a bare 1–5 rubric rating and
    # mapped to 0–1.
    if num > 1.0:
        num = (num - 1.0) / 4.0 if num <= 5.0 else 1.0
    return max(0.0, min(1.0, num))


def _run_judge(prompt: str) -> dict:
    """Run the LLM judge and parse {score, explanation}. Returns score=None on failure.

    Uses judge_chat_json → config.JUDGE_MODEL when set (a neutral third-family model,
    decoupled from the Qwen generator), else falls back to the generator chat model.
    """
    from agents.llm import judge_chat_json  # local import avoids load-time backend init
    try:
        result = judge_chat_json(prompt)  # temperature 0; routes to JUDGE_MODEL if set
        if isinstance(result, list) and result:
            result = result[0]
        if "score" not in result:
            raise ValueError(f"no 'score' key in judge result: {str(result)[:160]}")
        score = _coerce_score(result.get("score"))
        return {"score": score, "explanation": str(result.get("explanation", ""))[:200]}
    except Exception as exc:  # noqa: BLE001
        # Surface loudly — a silent n/a corrupts the aggregate mean.
        log.warning("JUDGE FAILED → scored as n/a: %s", exc)
        return {"score": None, "explanation": ""}


def judge_factuality(question: str, answer: str, gold: str) -> dict:
    """Paper Factuality (Appendix C): factual alignment of answer to gold, 0–1."""
    return _run_judge(_FACTUALITY_PROMPT.format(question=question, gold=gold, answer=answer))


def judge_context_recall(question: str, context: str, gold: str) -> dict:
    """Paper Context Recall (Appendix D): does retrieved context contain gold info, 0–1."""
    return _run_judge(_CONTEXT_RECALL_PROMPT.format(question=question, gold=gold, context=context))
